// Reproducible local Riot Data Dragon asset import. node tools/fetch_assets.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const version = '16.22.1';
const cdn = `https://ddragon.leagueoflegends.com/cdn/${version}`;
async function get(url) {
  for (let i = 0; i < 3; i++) {
    try { const r = await fetch(url, { signal: AbortSignal.timeout(30000) }); if (!r.ok) throw Error(`${r.status} ${url}`); return r; }
    catch (e) { if (i === 2) throw e; }
  }
}
async function save(url, dest) {
  const file = path.join(root, dest); await fs.mkdir(path.dirname(file), { recursive: true });
  try { if ((await fs.stat(file)).size > 0) return; } catch {}
  await fs.writeFile(file, Buffer.from(await (await get(url)).arrayBuffer()));
}
async function pool(list, fn, n = 8) { let i = 0; await Promise.all(Array.from({length:n}, async () => { while(i < list.length) await fn(list[i++]); })); }
const all = Object.values((await (await get(`${cdn}/data/ko_KR/champion.json`)).json()).data);
const versions = await (await get('https://ddragon.leagueoflegends.com/api/versions.json')).json();
const release = {};
for (let year = 2014; year <= 2026; year++) {
  const ver = versions.find(v => v.startsWith(`${year - 2010}.`));
  if (!ver) continue;
  const data = (await (await get(`https://ddragon.leagueoflegends.com/cdn/${ver}/data/en_US/champion.json`)).json()).data;
  for (const id of Object.keys(data)) if (!release[id]) release[id] = year;
}
const champions = {};
await save(`${cdn}/img/map/map11.png`, 'assets/maps/map11.png');
await pool(all, async c => {
  const detail = (await (await get(`${cdn}/data/ko_KR/champion/${c.id}.json`)).json()).data[c.id];
  await save(`${cdn}/img/champion/${c.image.full}`, `assets/champions/${c.id}.png`);
  const spells = detail.spells.map(s => ({ name:s.name, icon:s.image.full, cooldown:s.cooldown, range:s.range, description:s.description, tooltip:s.tooltip, cost:s.cost }));
  await pool(spells, s => save(`${cdn}/img/spell/${s.icon}`, `assets/spells/${s.icon}`), 2);
  await save(`${cdn}/img/passive/${detail.passive.image.full}`, `assets/passive/${detail.passive.image.full}`);
  champions[c.id] = { id:c.id, key:c.key, name:c.name, title:c.title, tags:c.tags, range:c.stats.attackrange, year:release[c.id] || 2026, spells, passive:{name:detail.passive.name, icon:detail.passive.image.full} };
  if (Object.keys(champions).length % 25 === 0) console.log(`Imported ${Object.keys(champions).length}/${all.length}`);
});
await fs.writeFile(path.join(root, 'data/champions.js'), `// Riot Data Dragon ${version}; generated by tools/fetch_assets.mjs\n(function(G){G.LFM_CHAMPIONS=${JSON.stringify({version, champions})};})(typeof window !== 'undefined' ? window : globalThis);\n`);
console.log(`Complete: ${all.length} champion portraits, ${all.length * 4} spell icons, ${all.length} passives.`);
